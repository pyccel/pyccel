def pyccel_test(
    test_file,
    dependencies=None,
    compile_with_pyccel=True,
    cwd=None,
    pyccel_commands="",
    output_dtype=float,
    language=None,
    *,
    isolated_dir,
):
    """
    Run pyccel and compare the output to ensure that the results
    are equivalent

    Parameters
    ----------
    test_file : str
                The name of the file containing the program.
                The path must either be absolute or relative
                to the folder containing this file
    dependencies : str/list
                The name of any files which are called by the
                test_file and must therefore be pyccelized in
                order to run it
                The paths must either be absolute or relative
                to the folder containing this file
    compile_with_pyccel : bool
                Indicates whether the compilation step should
                be handled by a basic call to gfortran/gcc (False)
                or internally by pyccel (True)
                default : True
    cwd : str
                The directory from which pyccel and other executables
                will be called
                default : The folder containing the test_file
    pyccel_commands : str
                Any additional commands which should be passed to
                pyccel
    output_dtype : type/list of types
                The types expected as output of the program.
                If one argument is provided then all types are
                assumed to be the same
    language : str
                The language pyccel should translate to
                default = 'fortran'
    isolated_dir : Path
                The test-exclusive directory (typically pytest's
                `tmp_path` fixture) into which test files are copied
                and pyccel is run
    """

    test_file = Path(test_file)
    rel_test_dir = test_file.parent

    if cwd is None:
        rel_cwd = rel_test_dir
    else:
        cwd = Path(cwd)
        rel_cwd = cwd.relative_to(get_abs_path("")) if cwd.is_absolute() else cwd

    pyth_out = get_python_output(get_abs_path(test_file), get_abs_path(rel_cwd))

    if language:
        pyccel_commands += " --language=" + language
    else:
        language = "fortran"

    test_file = copy_to_isolated_dir(isolated_dir, rel_test_dir, test_file)
    cwd = isolated_dir / rel_cwd.relative_to(rel_test_dir)
    output_dir = isolated_dir / "__pyccel__" if language == "python" else None

    if dependencies:
        if isinstance(dependencies, str):
            dependencies = [dependencies]
        for i, d in enumerate(dependencies):
            d = Path(d)
            if output_dir:
                rel_path = d.parent.relative_to(rel_test_dir)
                output = output_dir / rel_path
                pyc_command = pyccel_commands + " --output={}".format(output)
            else:
                pyc_command = pyccel_commands

            dependencies[i] = copy_to_isolated_dir(isolated_dir, rel_test_dir, d)

            if not compile_with_pyccel:
                compile_pyccel(cwd, dependencies[i], pyc_command + " -t")
                if language == "fortran":
                    generated_dep = insert_pyccel_folder(dependencies[i]).with_suffix(
                        ".f90"
                    )
                    compile_fortran(cwd, dependencies[i], generated_dep, [], is_mod=True)
                elif language == "c":
                    generated_dep = insert_pyccel_folder(dependencies[i]).with_suffix(
                        ".c"
                    )
                    compile_c(cwd, dependencies[i], generated_dep, [], is_mod=True)
            else:
                compile_pyccel(cwd, dependencies[i], pyc_command)

    if output_dir:
        pyccel_commands += " --output " + str(output_dir)
        output_test_file = output_dir / test_file.name
    else:
        output_test_file = test_file

    if compile_with_pyccel:
        compile_pyccel(cwd, test_file, pyccel_commands)
    else:
        compile_pyccel(cwd, test_file, pyccel_commands + " -t")
        if not dependencies:
            dependencies = []
        if language == "fortran":
            generated_file = insert_pyccel_folder(output_test_file).with_suffix(".f90")
            generated_dependencies = [
                insert_pyccel_folder(d).with_suffix(".f90") for d in dependencies
            ]
            compile_fortran(cwd, output_test_file, generated_file, generated_dependencies)
        elif language == "c":
            generated_file = insert_pyccel_folder(output_test_file).with_suffix(".c")
            generated_dependencies = [
                insert_pyccel_folder(d).with_suffix(".c") for d in dependencies
            ]
            compile_c(cwd, output_test_file, generated_file, generated_dependencies)

    lang_out = get_lang_output(output_test_file, language)
    compare_pyth_fort_output(pyth_out, lang_out, output_dtype, language)


