def get_exe(filename, language=None):
    filename = Path(filename)
    if language != "python":
        exefile1 = filename.with_suffix("")
        if sys.platform == "win32":
            exefile1 = exefile1.with_suffix(".exe")
    else:
        exefile1 = filename

    return exefile1


